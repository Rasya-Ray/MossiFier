"""
Synthetic Decision AI training for ESP32.
Install: pip install numpy pandas scikit-learn
Run: python train_model.py
Outputs: synthetic_dataset.csv, decision_model.h
IMPORTANT: synthetic labels are demo policies, NOT validated moss-care knowledge.
"""


import csv
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, _tree
from sklearn.metrics import accuracy_score, classification_report

SEED = 42
N_SAMPLES = 4000
FEATURES = ["cv_healthy", "cv_stressed", "cv_critical",
            "soil_pct", "mq135_raw", "pm25"]
rng = np.random.default_rng(SEED)

def make_dataset(n=N_SAMPLES):
    rows = []
    for _ in range(n):
        # CV outputs are percentages that sum to 100.
        probs = rng.dirichlet([1.4, 1.2, 0.8]) * 100
        healthy, stressed, critical = probs
        soil = rng.uniform(5, 95)
        mq135 = rng.uniform(150, 3500)  # raw ADC-like demo value
        pm25 = rng.uniform(0, 180)      # ug/m3, synthetic
        # DEMO target policy. Replace with expert/experimental labels later.
        pump = int(soil < 35)

        if pm25 >= 75:
            fan = 0  # avoid bringing in heavily polluted outside air
        elif mq135 >= 2200:
            fan = 200
        elif critical >= 55:
            fan = 128
        else:
            fan = 64

        if critical >= 60:
            light = 255
        elif stressed >= 45 or critical >= 25:
            light = 200
        elif healthy >= 80:
            light = 64
        else:
            light = 128

        rows.append([healthy, stressed, critical, soil, mq135, pm25,
                     fan, light, pump])
    return rows

def emit_tree(model, function_name, output_path):
    tree = model.tree_
    classes = model.classes_
    lines = []
    lines.append(f"inline int {function_name}(const float x[6]) {{")
    def walk(node, depth):
        indent = "  " * (depth + 1)
        feature = tree.feature[node]
        if feature == _tree.TREE_UNDEFINED:
            counts = tree.value[node][0]
            pred_index = int(np.argmax(counts))
            pred = int(classes[pred_index])
            lines.append(indent + f"return {pred};")
            return
        fname = FEATURES[feature]
        threshold = float(tree.threshold[node])
        lines.append(indent + f"if (x[{feature}] <= {threshold:.8f}f) {{ // {fname}")
        walk(tree.children_left[node], depth + 1)
        lines.append(indent + "} else {")
        walk(tree.children_right[node], depth + 1)
        lines.append(indent + "}")
    walk(0, 0)
    lines.append("}")
    return "\n".join(lines)

def main():
    rows = make_dataset()
    with open("synthetic_dataset.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(FEATURES + ["fan_pwm", "light_pwm", "pump"])
        w.writerows(rows)

    data = np.array([r[:6] for r in rows], dtype=float)
    targets = {
        "fan": np.array([r[6] for r in rows], dtype=int),
        "light": np.array([r[7] for r in rows], dtype=int),
        "pump": np.array([r[8] for r in rows], dtype=int),
    }

    x_train, x_test, idx_train, idx_test = train_test_split(
        data, np.arange(len(data)), test_size=0.2, random_state=SEED
    )

    models = {}
    for name, y in targets.items():
        model = DecisionTreeClassifier(
            max_depth=6, min_samples_leaf=10, random_state=SEED
        )
        model.fit(x_train, y[idx_train])
        pred = model.predict(x_test)
        print(f"{name} accuracy: {accuracy_score(y[idx_test], pred):.3f}")
        print(classification_report(y[idx_test], pred, zero_division=0))
        models[name] = model

    header = [
        "#pragma once",
        "// Generated by train_model.py. Do not edit manually.",
        "// Feature order: healthy%, stressed%, critical%, soil%, MQ135 raw, PM2.5 ug/m3",
        "namespace DecisionAI {",
        "inline int predictFan(const float x[6]) {",
    ]
    # emit function bodies separately to keep generated header readable
    bodies = []
    for name, model in models.items():
        bodies.append(emit_tree(model, "predictFan" if name == "fan" else
                                "predictLight" if name == "light" else "predictPump", None))
    header = [
        "#pragma once",
        "// Generated by train_model.py. Synthetic demo model; validate before real use.",
        "// x[0]=CV healthy %, x[1]=CV stressed %, x[2]=CV critical %",
        "// x[3]=soil moisture %, x[4]=MQ135 raw ADC, x[5]=PMS5003 PM2.5 ug/m3",
        "namespace DecisionAI {",
        *bodies,
        "} // namespace DecisionAI",
    ]
    with open("decision_model.h", "w") as f:
        f.write("\n\n".join(header) + "\n")
    print("Generated decision_model.h")

if __name__ == "__main__":
    main()
